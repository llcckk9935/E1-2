from quiz import Quiz


def make_default_quizzes():
    """기본 퀴즈 5개를 담은 리스트를 새로 만들어 돌려주는 기능입니다.

    각 Quiz는 (문제, 선택지 4개, 정답 번호, 힌트) 순서로 만듭니다.
    """
    # 호출할 때마다 새 객체를 만들어 게임 사이에 목록을 공유하지 않습니다.
